@cocotb.test()
async def kat_independence(dut):
    """D4: the far end's modules import only the standard library, cocotb and
    each other -- no RTL-derived helper and no other bench file."""
    mods = sorted(f for f in os.listdir(HERE) if f.startswith('lr1_') and f.endswith('.py'))
    check(len(mods) >= 5, 'expected the lr1_*.py modules beside this file, found %s' % mods)
    for m in mods:
        with open(os.path.join(HERE, m)) as fh:
            tree = ast.parse(fh.read())
        for node in ast.walk(tree):
            names = []
            if isinstance(node, ast.Import):
                names = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom):
                names = [node.module or '']
            for n in names:
                ok = n in STDLIB_OK or n in COCOTB_OK or n.startswith('lr1_')
                check(ok, '%s imports %s, outside D4' % (m, n))
