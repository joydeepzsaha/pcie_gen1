    a6 = vectors()['tlp_headers'][0]
    check(TLP.cfg_req(False, False, 0, 0, 0, 0, 0, 0, td=1).hex() == a6['hex'], 'cfg_req rebuilds A-6')
    cpl = vectors()['tlp_headers'][1]
    check(TLP.cpl(0, C.CPL_SC, 1, 4, 4, td=1).hex() == cpl['hex'], 'cpl rebuilds the pcievhost Cpl')
    cpld = vectors()['tlp_headers'][2]
    check(TLP.cpl(0, C.CPL_SC, 1, 5, 4, data=H('00f0aa55'), td=1).hex() == cpld['hex'] + '00f0aa55',
          'cpl rebuilds the pcievhost CplD')
    from cocotbext.pcie.core.tlp import Tlp, TlpType, CplStatus
    from cocotbext.pcie.core.utils import PcieId
    rnd = random.Random(0x11A4)
    for _ in range(300):
        bus, dev, fn, reg = rnd.randrange(256), rnd.randrange(32), rnd.randrange(8), rnd.randrange(1024) * 4
        rid, tag, be = rnd.randrange(65536), rnd.randrange(256), rnd.randrange(16)
