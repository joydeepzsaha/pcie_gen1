@cocotb.test()
async def kat_cfg_completion(dut):
    """The Transaction Layer (lr1_cfg) answers a CfgRd0 the way PG213 did
    (ruling A's joint run): the same CplD bytes, so the CplD header layout,
    Byte Count 4 (p.97) and the payload byte order (byte 0 = register bits
    [7:0]) are K."""
    import lr1_cfg as CFG
    from lr1_farend import Knobs
    v = vectors()['pg213_cpld']
    comp = CFG.Completer(Knobs(), lambda s: None, lambda: 0)
    comp.cfg.val[0x00] = v['register_000h']
    r = v['request']
    req = TLP.parse(TLP.cfg_req(False, False, r['req_id'], r['tag'], r['bus'], r['dev'], r['fn'], r['reg']))
    out = comp.handle(req)
    check(len(out) == 1, 'one completion expected, got %d' % len(out))
    check(out[0].hex() == v['tlp'], 'CplD %s, PG213 sent %s' % (out[0].hex(), v['tlp']))
    # the negative control: the other byte order is not what PG213 sent
    swapped = out[0][:12] + out[0][12:16][::-1]
    check(swapped.hex() != v['tlp'], 'the vector cannot tell the byte orders apart')


@cocotb.test()
async def kat_framing(dut):
    """x1 framing (§4.2.2 pp.195-196, Figures 4-6 / 4-7 p.197)."""
    v = vectors()['lcrc'][1]                      # pcievhost seq 4 Cpl
    tlp = H(v['tlp'])
    f = SYM.frame_tlp(v['seq'], tlp)
    want = [(C.STP, 1), (0x00, 0), (0x04, 0)] + [(b, 0) for b in tlp + H(v['lcrc'])] + [(C.END, 1)]
    check(f == want, 'frame_tlp')
    n = SYM.frame_tlp(v['seq'], tlp, nullify=True)
    check(n[-1] == (C.EDB, 1) and bytes(b for b, _ in n[-5:-1]) == bytes(x ^ 0xFF for x in H(v['lcrc'])),
          'nullified frame: EDB and the inverted LCRC (p.174)')
    d = SYM.frame_dllp(H('00000003'))
    check(d == [(C.SDP, 1)] + [(b, 0) for b in H('00000003504e')] + [(C.END, 1)], 'frame_dllp Ack 3')
    check(len(SYM.frame_dllp(H('00000000'))) == 8, 'a framed DLLP is 8 Symbols (p.196)')
    check(SYM.skp_os() == [(C.COM, 1)] + [(C.SKP, 1)] * 3 and SYM.eios() == [(C.COM, 1)] + [(C.IDL, 1)] * 3,
          'SKP OS / EIOS (§4.2.7.1 p.261, Table 4-4 p.205)')
    t = SYM.ts1(link=0, lane=None, n_fts=0x80)
    check(t == [(C.COM, 1), (0, 0), (C.PAD, 1), (0x80, 0), (0x02, 0), (0, 0)] + [(0x4A, 0)] * 10, 'TS1 layout')
    check(SYM.parse_ts(t)['lane'] is None and SYM.parse_ts(t)['link'] == 0, 'parse_ts')


