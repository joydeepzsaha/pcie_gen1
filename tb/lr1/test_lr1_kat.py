def _fields_to_dllp(f):
    if f['kind'] == 'Ack':
        return SYM.dllp_ack(f['seq'])
    return SYM.updatefc(f['fc'], f['hdr'], f['data'])


@cocotb.test()
async def kat_dllp_crc(dut):
    """DLLP CRC (§3.4.1 p.167, Table 3-2 p.168) against 19 outside vectors and cocotbext-pcie."""
    n = 0
    for v in vectors()['dllp_crc']:
        b4 = H(v['dllp']) if 'dllp' in v else _fields_to_dllp(v['fields'])
        got = CRC.dllp_crc(b4).hex()
        check(got == v['crc'], '%s: dllp_crc(%s) = %s, vector %s' % (v['name'], b4.hex(), got, v['crc']))
        check(CRC.dllp_ok(b4 + H(v['crc'])), v['name'] + ': dllp_ok rejects the vector')
        n += 1
    check(n == 19, 'expected 19 DLLP CRC vectors, have %d' % n)
    # Third-party implementation (cocotbext-pcie 0.2.16, MIT): crc16 returns the
    # uncomplemented register in the wire's little-endian sense.
    from cocotbext.pcie.core.dllp import crc16 as cx_crc16
    rnd = random.Random(0x11A1)
    for _ in range(2000):
        b4 = bytes(rnd.getrandbits(8) for _ in range(4))
        cx = struct.pack('<H', (~cx_crc16(b4)) & 0xFFFF)
        check(CRC.dllp_crc(b4) == cx, 'cocotbext-pcie disagrees on %s' % b4.hex())


@cocotb.test()
async def kat_lcrc(dut):
    """LCRC (§3.5.2.1 pp.171-173, Table 3-3) against MindShare A-6, pcievhost and zlib."""
    vs = vectors()['lcrc']
    check(len(vs) == 4, 'expected 4 LCRC vectors')
    for v in vs:
        tlp = H(v['tlp'])
        got = CRC.lcrc(v['seq'], tlp).hex()
        check(got == v['lcrc'], '%s: lcrc = %s, vector %s' % (v['name'], got, v['lcrc']))
        framed = CRC.seq_bytes(v['seq']) + tlp + H(v['lcrc'])
        check(CRC.lcrc_ok(framed), v['name'] + ': lcrc_ok rejects the vector')
        check(not CRC.lcrc_nullified(framed), v['name'] + ': a good TLP reads as nullified')
        # Nullified (p.174, R): the inverted LCRC is recognised, and only as nullified.
        nul = CRC.seq_bytes(v['seq']) + tlp + CRC.nullified_lcrc(v['seq'], tlp)
        check(CRC.lcrc_nullified(nul) and not CRC.lcrc_ok(nul), v['name'] + ': nullified LCRC not recognised')
    # zlib is a generic CRC-32 engine; agreeing with it over random data shows the
    # bit-serial form is the standard reflected CRC-32 (R-vs-library). The K is above.
    rnd = random.Random(0x11A2)
    for _ in range(2000):
        seq = rnd.randrange(4096)
        tlp = bytes(rnd.getrandbits(8) for _ in range(rnd.randint(12, 80)))
        z = struct.pack('<I', zlib.crc32(CRC.seq_bytes(seq) + tlp))
        check(CRC.lcrc(seq, tlp) == z, 'zlib disagrees at seq %d' % seq)
    # seq[11:8] placement: no outside vector has seq >= 256 (PHASE0 §4.3, R).
    check(CRC.seq_bytes(0xABC) == bytes([0x0A, 0xBC]), 'seq_bytes layout')


def _serial_msb_first(data, poly, width, seed):
    top, mask, c = 1 << (width - 1), (1 << width) - 1, seed
    for b in data:
        for i in range(7, -1, -1):
            fb = ((b >> i) & 1) ^ (1 if c & top else 0)
            c = (c << 1) & mask
            if fb:
                c ^= poly
    return c


@cocotb.test()
async def kat_crc_misreadings(dut):
    """Each plausible misreading of either CRC misses at least one outside vector."""
    V = vectors()
    lv = [(CRC.seq_bytes(v['seq']) + H(v['tlp']), H(v['lcrc'])) for v in V['lcrc']]
    dv = [(H(v['dllp']), H(v['crc'])) for v in V['dllp_crc'] if 'dllp' in v]
    S, M = CRC._serial, CRC._map_field
    lcrc_mis = {
        'no complement': lambda d: M(S(d, C.LCRC_POLY, 32, C.LCRC_SEED), 32).to_bytes(4, 'big'),
        'no bit-reverse map': lambda d: (S(d, C.LCRC_POLY, 32, C.LCRC_SEED) ^ 0xFFFFFFFF).to_bytes(4, 'big'),
        'field byte order swapped': lambda d: CRC.lcrc_over(d)[::-1],
        'seed 0': lambda d: M(S(d, C.LCRC_POLY, 32, 0) ^ 0xFFFFFFFF, 32).to_bytes(4, 'big'),
        'bit 7 first': lambda d: M(_serial_msb_first(d, C.LCRC_POLY, 32, C.LCRC_SEED) ^ 0xFFFFFFFF, 32).to_bytes(4, 'big'),
        'sequence bytes excluded': lambda d: CRC.lcrc_over(d[2:]),
        'reserved nibble = FFh': lambda d: CRC.lcrc_over(bytes([d[0] | 0xF0]) + d[1:]),
    }
    dllp_mis = {
        'byte order swapped': lambda b: CRC.dllp_crc(b)[::-1],
        'no complement': lambda b: M(S(b, C.DLLP_CRC_POLY, 16, C.DLLP_CRC_SEED), 16).to_bytes(2, 'big'),
        'no bit-reverse map': lambda b: (S(b, C.DLLP_CRC_POLY, 16, C.DLLP_CRC_SEED) ^ 0xFFFF).to_bytes(2, 'big'),
        'bit 7 first': lambda b: M(_serial_msb_first(b, C.DLLP_CRC_POLY, 16, C.DLLP_CRC_SEED) ^ 0xFFFF, 16).to_bytes(2, 'big'),
        'seed 0': lambda b: M(S(b, C.DLLP_CRC_POLY, 16, 0) ^ 0xFFFF, 16).to_bytes(2, 'big'),
        'CCITT 1021h (binascii.crc_hqx)': lambda b: struct.pack('>H', binascii.crc_hqx(b, 0xFFFF) ^ 0xFFFF),
    }
    for name, f in lcrc_mis.items():
        misses = sum(1 for d, e in lv if f(d) != e)
        check(misses >= 1, 'LCRC misreading "%s" matches every vector' % name)
        # the arbitrary-data vector alone (A-6) must discriminate
        check(f(lv[0][0]) != lv[0][1], 'LCRC misreading "%s" matches MindShare A-6' % name)
    for name, f in dllp_mis.items():
        check(sum(1 for b, e in dv if f(b) != e) >= 1, 'DLLP misreading "%s" matches every vector' % name)


