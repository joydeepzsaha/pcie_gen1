@cocotb.test()
async def kat_scrambler_p700(dut):
    """LFSR (§4.2.3, Fig. 4-10) against both Appendix C tables (p.700)."""
    V = vectors()
    states, zeros = V['p700_lfsr_states']['values'], V['p700_scrambled_zeros']['values']
    check(len(states) == 128 and len(zeros) == 304, 'table sizes')
    l = 0xFFFF
    for i in range(max(len(states), len(zeros))):
        if i < len(states):
            check(l == states[i], 'LFSR state %d: %04x, table %04x' % (i, l, states[i]))
        mask, l2 = SCR.lfsr_byte(l)
        if i < len(zeros):
            check(mask == zeros[i], 'scrambled zero %d: %02x, table %02x' % (i, mask, zeros[i]))
        l = l2
    # through the Symbol-level transmitter: COM then 304 zeros
    tx = SCR.TxScrambler()
    tx.symbol(C.COM, 1)
    out = [tx.symbol(0, 0) for _ in range(304)]
    check(out == zeros, 'TxScrambler after COM does not reproduce p.700')


# ======================================================== PG213 (ruling C)
def pg213_segments(which):
    """[(kind, [(byte, k)...]), ...] from the filed capture; the PRE fragment
    before the first COM is dropped (no LFSR reference)."""
    meta = vectors()['pg213_symbol_files'][which]
    path = os.path.join(HERE, meta['file'])
    import hashlib
    with open(path, 'rb') as f:
        raw = f.read()
    check(hashlib.md5(raw).hexdigest() == meta['md5'], 'PG213 vector file md5 differs from kat_vectors.json')
    segs = []
    for ln in raw.decode().splitlines():
        if ln.startswith('#') or not ln.strip():
            continue
        t, lane, kind, syms, _ = ln.split('|')
        if kind == 'PRE':
            continue
        segs.append((kind, [(int(s[1:], 16), 1) if s.startswith('K') else (int(s, 16), 0) for s in syms.split()]))
    return segs


def classify(seg):
    """The far end's receive-side split of one COM-led segment (raw Symbols):
    returns (kind, os_len, fields)."""
    if len(seg) >= 2 and seg[1] == (C.SKP, 1):
        n = 1
        while n < len(seg) and seg[n] == (C.SKP, 1):
            n += 1
        return 'SKP', n, n - 1
    f = SYM.parse_ts(seg[:16])
    if f is not None:
        return f['kind'], 16, f
    return 'OTHER', 1, None


@cocotb.test()
async def kat_pg213_receive(dut):
    """The receive side (RxDescrambler, parse_ts) over PG213's transmit stream:
    every segment is a TS1, TS2 or SKP OS, and every Logical Idle Symbol
    descrambles to 00h (§4.2.2 p.195)."""
    expect = {'fast': {'TS1': 75, 'TS2': 45, 'SKP': 7}, 'slow': {'TS1': 103, 'TS2': 1026, 'SKP': 21}}
    for which in ('fast', 'slow'):
        rx = SCR.RxDescrambler()
        counts, idle, nonzero = {}, 0, 0
        runs = []
        for kind, seg in pg213_segments(which):
            k2, osl, f = classify(seg)
            check(k2 == kind, '%s: segment classified %s, capture says %s' % (which, k2, kind))
            counts[k2] = counts.get(k2, 0) + 1
            plain = [rx.feed(b, k) for b, k in seg]
            # TS bodies come out untouched; the descrambler found them itself
            if k2 in ('TS1', 'TS2'):
                check(all(p[2] for p in plain[1:16]) and not plain[0][2], 'TS body not recognised')
                check([(p[0], p[1]) for p in plain[:16]] == seg[:16], 'a TS was altered by the descrambler')
                key = (k2, f['link'], f['lane'], f['n_fts'], f['rate'], f['tc'])
                if runs and runs[-1][0] == key:
                    runs[-1][1] += 1
                else:
                    runs.append([key, 1])
            for p, k, in_ts in plain[osl:]:
                check(not k, '%s: a K code inside Logical Idle' % which)
                idle += 1
                nonzero += (p != 0)
        check(counts == expect[which], '%s: counts %s, expected %s' % (which, counts, expect[which]))
        check(idle > 6000 and nonzero == 0, '%s: %d idle Symbols, %d not 00h' % (which, idle, nonzero))
        # The upstream port's training sequence as PG213 sends it (Base 2.1 §4.2.6):
        # PAD/PAD TS1 -> PAD/PAD TS2 -> PAD/PAD TS1 -> link 0, lane PAD -> link 0, lane 0 -> TS2 0/0.
        shape = [(k[0], k[1], k[2]) for k, _ in runs]
        check(shape == [('TS1', None, None), ('TS2', None, None), ('TS1', None, None),
                        ('TS1', 0, None), ('TS1', 0, 0), ('TS2', 0, 0)], '%s: TS run shape %s' % (which, shape))
        check(all(k[3] == 0xFF and k[5] == 0 and k[4] in (0x02, 0x42) for k, _ in runs), 'TS N_FTS / rate / TC')


def regenerate(segs, scrambler_cls=SCR.TxScrambler, ts_builder=None):
    """Rebuild a captured stream from its structure with the far end's own
    transmit builders, scramble it, and return the Symbol list."""
    tx = scrambler_cls()
    out = []
    for kind, seg in segs:
        k2, osl, f = classify(seg)
        if k2 == 'SKP':
            plain = [(b, k, False) for b, k in SYM.skp_os(f)]
        else:
            ident = C.TS1_ID if k2 == 'TS1' else C.TS2_ID
            build = ts_builder or SYM.ts
            plain = [(b, k, i > 0) for i, (b, k) in enumerate(
                build(ident, link=f['link'], lane=f['lane'], n_fts=f['n_fts'], rate=f['rate'], tc=f['tc']))]
        plain += [(b, k, False) for b, k in SYM.idle(len(seg) - osl)]
        out.extend((tx.symbol(b, k, in_ts), k) for b, k, in_ts in plain)
    return out


@cocotb.test()
async def kat_pg213_transmit(dut):
    """The transmit side (ts / skp_os / idle + TxScrambler) regenerates PG213's
    stream byte for byte: TS layout (Tables 4-2 / 4-3) and the scrambler rules
    (§4.2.3 p.199: COM reseeds, SKP does not advance, TS bodies advance
    unscrambled) are K."""
    for which in ('fast', 'slow'):
        segs = pg213_segments(which)
        want = [s for _, seg in segs for s in seg]
        got = regenerate(segs)
        check(len(got) == len(want), 'length')
        bad = [i for i, (a, b) in enumerate(zip(got, want)) if a != b]
        check(not bad, '%s: %d Symbols differ, first at %s' % (which, len(bad), bad[:3]))


class _NoTsAdvance(SCR.Scrambler):
    def symbol(self, byte, k, in_ts=False):
        if in_ts and not k:
            return byte
        return super().symbol(byte, k, in_ts)


class _SkpAdvances(SCR.Scrambler):
    def symbol(self, byte, k, in_ts=False):
        if k and byte == C.SKP:
            self.lfsr = SCR.lfsr_byte(self.lfsr)[1]
            return byte
        return super().symbol(byte, k, in_ts)


class _NoComReset(SCR.Scrambler):
    def symbol(self, byte, k, in_ts=False):
        if k and byte == C.COM:
            self.lfsr = SCR.lfsr_byte(self.lfsr)[1]
            return byte
        return super().symbol(byte, k, in_ts)


class _MaskReversed(SCR.Scrambler):
    def symbol(self, byte, k, in_ts=False):
        if k or in_ts:
            return super().symbol(byte, k, in_ts)
        mask, nxt = SCR.lfsr_byte(self.lfsr)
        rev = int('{:08b}'.format(mask)[::-1], 2)
        self.lfsr = nxt
        return byte ^ rev


@cocotb.test()
async def kat_pg213_power(dut):
    """The PG213 vector discriminates: each misreading of the scrambler rules or
    the TS layout fails to regenerate the stream."""
    segs = pg213_segments('fast')
    want = [s for _, seg in segs for s in seg]
    for cls, name in ((_NoTsAdvance, 'TS bodies do not advance the LFSR'),
                      (_SkpAdvances, 'SKP advances the LFSR'),
                      (_NoComReset, 'COM does not reseed'),
                      (_MaskReversed, 'LFSR output bit order reversed')):
        check(regenerate(segs, scrambler_cls=cls) != want, 'scrambler misreading "%s" regenerates PG213' % name)

    def ts_rate_tc_swapped(ident, link, lane, n_fts, rate, tc):
        return SYM.ts(ident, link=link, lane=lane, n_fts=n_fts, rate=tc, tc=rate)

    def ts_nine_ids(ident, link, lane, n_fts, rate, tc):
        s = SYM.ts(ident, link=link, lane=lane, n_fts=n_fts, rate=rate, tc=tc)
        return s[:6] + [(0x00, 0)] + s[7:]
    for b, name in ((ts_rate_tc_swapped, 'Symbols 4 and 5 swapped'), (ts_nine_ids, 'Symbol 6 not an identifier')):
        check(regenerate(segs, ts_builder=b) != want, 'TS misreading "%s" regenerates PG213' % name)


