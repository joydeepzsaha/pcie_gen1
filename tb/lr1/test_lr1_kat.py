@cocotb.test()
async def kat_dllp_layout(dut):
    """DLLP fields (Figures 3-5..3-8 p.166) against the explicit outside bytes
    and cocotbext-pcie's packer."""
    exp = {'400803f0': ('InitFC1', 'P', 32, 1008), '50080001': ('InitFC1', 'NP', 32, 1),
           '60000000': ('InitFC1', 'CPL', 0, 0), 'c00803f0': ('InitFC2', 'P', 32, 1008),
           'd0080001': ('InitFC2', 'NP', 32, 1), 'e0000000': ('InitFC2', 'CPL', 0, 0)}
    for hx, (ph, fct, hdr, data) in exp.items():
        b = (SYM.initfc1 if ph == 'InitFC1' else SYM.initfc2)(fct, hdr, data)
        check(b.hex() == hx, '%s-%s %d/%d builds %s, vector %s' % (ph, fct, hdr, data, b.hex(), hx))
        d = SYM.parse_dllp(b + CRC.dllp_crc(b))
        check((d['kind'], d['fc'], d['hdr'], d['data'], d['crc_ok'], d['rsvd_nonzero']) ==
              (ph, fct, hdr, data, True, False), 'parse_dllp round trip ' + hx)
    check(SYM.dllp_ack(3).hex() == '00000003' and SYM.dllp_ack(5).hex() == '00000005', 'Ack layout')
    # pcievhost's UpdateFC-NP: bytes and CRC are K; its decode is cut off in the
    # screenshot, so HdrFC 37 / DataFC 4 are our reading of Fig. 3-8 (R).
    d = SYM.parse_dllp(H('90094004') + H('4b53'))
    check((d['kind'], d['fc'], d['hdr'], d['data'], d['crc_ok']) == ('UpdateFC', 'NP', 37, 4, True), 'UpdateFC-NP vector')
    # Reserved bits (Figures 3-5..3-8): each one, alone, is detected
    for rs in ({'rsvd1': 1}, {'rsvd1': 0x80}, {'rsvd2': 1}, {'rsvd2': 8}):
        b = SYM.dllp_ack(7, **rs)
        check(SYM.parse_dllp(b + CRC.dllp_crc(b))['rsvd_nonzero'], 'Ack reserved %s not detected' % rs)
    for rs in ({'rsvd1': 1}, {'rsvd1': 2}, {'rsvd2': 1}, {'rsvd2': 2}):
        b = SYM.updatefc('P', 0x7F, 0x7FF, **rs)
        d = SYM.parse_dllp(b + CRC.dllp_crc(b))
        check(d['rsvd_nonzero'] and d['hdr'] == 0x7F and d['data'] == 0x7FF, 'FC reserved %s' % rs)
    # Third-party packer (cocotbext-pcie Dllp)
    from cocotbext.pcie.core.dllp import Dllp, DllpType
    cx = {('InitFC1', 'P'): DllpType.INIT_FC1_P, ('InitFC1', 'NP'): DllpType.INIT_FC1_NP,
          ('InitFC1', 'CPL'): DllpType.INIT_FC1_CPL, ('InitFC2', 'P'): DllpType.INIT_FC2_P,
          ('InitFC2', 'NP'): DllpType.INIT_FC2_NP, ('InitFC2', 'CPL'): DllpType.INIT_FC2_CPL,
          ('UpdateFC', 'P'): DllpType.UPDATE_FC_P, ('UpdateFC', 'NP'): DllpType.UPDATE_FC_NP,
          ('UpdateFC', 'CPL'): DllpType.UPDATE_FC_CPL}
    build = {'InitFC1': SYM.initfc1, 'InitFC2': SYM.initfc2, 'UpdateFC': SYM.updatefc}
    rnd = random.Random(0x11A3)
    for _ in range(500):
        (ph, fct), t = rnd.choice(sorted(cx.items(), key=lambda x: x[0]))
        hdr, data = rnd.randrange(256), rnd.randrange(4096)
        x = Dllp()
        x.type, x.vc, x.hdr_fc, x.data_fc = t, 0, hdr, data
        mine = build[ph](fct, hdr, data)
        check(mine + CRC.dllp_crc(mine) == bytes(x.pack_crc()), 'cocotbext-pcie %s-%s %d/%d' % (ph, fct, hdr, data))
    for seq in (0, 1, 255, 256, 2047, 4095):
        x = Dllp.create_ack(seq)
        mine = SYM.dllp_ack(seq)
        check(mine + CRC.dllp_crc(mine) == bytes(x.pack_crc()), 'cocotbext-pcie Ack %d' % seq)


